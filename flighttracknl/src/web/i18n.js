let lang = 'nl';
export function getLang() { return lang; }
export function setLang(next) {
  lang = DICT[next] ? next : 'nl';
  document.documentElement.lang = lang;
}

export function t(key, vars) {
  const table = DICT[lang] || NL;
  let s = table[key];
  if (s === undefined) s = NL[key];
  if (s === undefined) return key;
  if (Array.isArray(s)) return s;
  return vars ? s.replace(/\{(\w+)\}/g, (_, k) => vars[k]) : s;
}

export function applyStatic(root = document) {
  for (const el of root.querySelectorAll('[data-i18n]')) el.textContent = t(el.dataset.i18n);
  // Alleen voor teksten uit dit bestand: de bronnenlijst moet echte links kunnen dragen,
  // want CARTO, OpenStreetMap en adsb.fi schrijven een vermelding met link voor.
  for (const el of root.querySelectorAll('[data-i18n-html]')) el.innerHTML = t(el.dataset.i18nHtml);
  for (const el of root.querySelectorAll('[data-i18n-title]')) el.title = t(el.dataset.i18nTitle);
  for (const el of root.querySelectorAll('[data-i18n-aria]')) el.setAttribute('aria-label', t(el.dataset.i18nAria));
}
